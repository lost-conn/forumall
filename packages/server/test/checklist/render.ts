/** "Provider **MUST**" → "Provider MUST". */
export function levelTitle(level: Level): string {
  return LEVEL_HEADINGS[level].replaceAll("**", "");
}

export function countByStatus(entries: readonly ChecklistEntry[]): Record<Status, number> {
  const counts = { covered: 0, partial: 0, missing: 0 };
  for (const e of entries) counts[e.status] += 1;
  return counts;
}

function renderEntry(entry: ChecklistEntry, index: number): string {
  const lines = [`${index + 1}. **${entry.status}**: ${entry.item}`];
  if (entry.covers.length > 0) {
    lines.push(`    - Tests: ${entry.covers.map((f) => `\`${f}\``).join(", ")}`);
  }
  if (entry.note) lines.push(`    - Note: ${entry.note}`);
  if (entry.context) lines.push(`    - Context: ${entry.context}`);
  return lines.join("\n");
}

function renderSummary(entries: readonly ChecklistEntry[]): string {
  const rows = LEVELS.map((level) => {
    const ofLevel = entries.filter((e) => e.level === level);
    const c = countByStatus(ofLevel);
    return `| ${levelTitle(level)} | ${ofLevel.length} | ${STATUSES.map((s) => c[s]).join(" | ")} |`;
  });
  const total = countByStatus(entries);
  return [
    "## Summary",
    "",
    "| Level | Items | Covered | Partial | Missing |",
    "|---|---|---|---|---|",
    ...rows,
    `| **Total** | ${entries.length} | ${STATUSES.map((s) => total[s]).join(" | ")} |`,
  ].join("\n");
}

function renderLevel(entries: readonly ChecklistEntry[], level: Level): string {
  const ofLevel = entries.filter((e) => e.level === level);
  return [`### ${levelTitle(level)} (${ofLevel.length} items)`, "", ...ofLevel.map(renderEntry)]
    .join("\n")
    .concat("\n");
}

/** The full CONFORMANCE.md text for a coverage map. */
export function renderConformance(entries: readonly ChecklistEntry[]): string {
  return [
    HEADER,
    renderSummary(entries),
    "",
    "## §12 Compliance Checklist coverage map",
    "",
    LEVELS.map((level) => renderLevel(entries, level)).join("\n"),
    FOOTER,
  ].join("\n");
}
